package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// The MCP tool list_api shows mcpRoutes (apiroutes.go): the GUI's API as registered in the source.  This test finds the
// routes in the source and fails when the list is out of date; DNSDIR_UPDATE_ROUTES=1 writes it again.
func TestAPIRoutesListed(t *testing.T) {
	files, _ := filepath.Glob("*.go")
	re := regexp.MustCompile(`HandleFunc\("(?:(GET|POST|PUT|DELETE) )?(/api/[^"]*)"(.*)$`)
	qre := regexp.MustCompile(`w\.op\("[^"]+", \[\]string\{([^}]*)\}\)`)
	var got []apiRoute
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		for _, line := range strings.Split(string(b), "\n") {
			m := re.FindStringSubmatch(line)
			if m == nil || mcpRouteHidden(m[2]) {
				continue
			}
			r := apiRoute{Method: m[1], Path: m[2]}
			if r.Method == "" {
				r.Method = "GET POST"
			}
			if q := qre.FindStringSubmatch(m[3]); q != nil {
				for _, s := range strings.Split(q[1], ",") {
					if s = strings.Trim(strings.TrimSpace(s), `"`); s != "" {
						r.Query = append(r.Query, s)
					}
				}
			}
			got = append(got, r)
		}
	}
	sort.Slice(got, func(i, j int) bool {
		if got[i].Path != got[j].Path {
			return got[i].Path < got[j].Path
		}
		return got[i].Method < got[j].Method
	})
	var sb strings.Builder
	sb.WriteString("// Code generated by TestAPIRoutesListed (DNSDIR_UPDATE_ROUTES=1 go test -run TestAPIRoutesListed); DO NOT EDIT.\n\npackage main\n\n// mcpRoutes is the GUI's API, for the MCP tool list_api (mcp.go).\nvar mcpRoutes = []apiRoute{\n")
	for _, r := range got {
		q := ""
		if len(r.Query) > 0 {
			q = fmt.Sprintf(", Query: []string{%q}", r.Query)
			q = strings.ReplaceAll(strings.ReplaceAll(q, `{["`, `{"`), `"]}`, `"}`)
			q = strings.ReplaceAll(q, `" "`, `", "`)
		}
		fmt.Fprintf(&sb, "\t{Method: %q, Path: %q%s},\n", r.Method, r.Path, q)
	}
	sb.WriteString("}\n")
	want := sb.String()
	have, _ := os.ReadFile("apiroutes.go")
	if string(have) == want {
		return
	}
	if os.Getenv("DNSDIR_UPDATE_ROUTES") == "1" {
		if err := os.WriteFile("apiroutes.go", []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Fatal("apiroutes.go is out of date: run DNSDIR_UPDATE_ROUTES=1 go test -run TestAPIRoutesListed")
}
